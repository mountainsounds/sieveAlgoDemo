/**
 * Seeded PRNG shared by the algorithms that generate their own input. Every
 * demo array is a pure function of its controls, so a reload, a deep link, or
 * a screenshot always reproduces the run you just watched.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
